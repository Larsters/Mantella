"""On-disk cache of generated bios: one editable JSON file per NPC per world.

<save_folder>/data/Skyrim/generated_bios/<world_id>/<NPC name> - <ref_id>.json

Users may edit "bio" / "personality_and_speech", set "enabled": false to go back to the original bio,
or delete the file to have it generated again.
"""
from __future__ import annotations

import json
import os
import re
import tempfile
from datetime import datetime
from typing import Any

import src.utils as utils

logger = utils.get_logger()

SCHEMA_VERSION = 1
_UNSAFE = re.compile(r'[<>:"/\\|?*\x00-\x1f]')


def _safe(part: str) -> str:
    return _UNSAFE.sub("_", str(part)).strip(" .") or "_"


class BioStore:
    def __init__(self, root_folder: str):
        self.__root = root_folder

    @property
    def root(self) -> str:
        return self.__root

    def path_for(self, world_id: str, name: str, ref_id: str) -> str:
        return os.path.join(self.__root, _safe(world_id or "default"), f"{_safe(name)} - {_safe(ref_id)}.json")

    def load(self, world_id: str, name: str, ref_id: str) -> dict[str, Any] | None:
        path = self.path_for(world_id, name, ref_id)
        if not os.path.exists(path):
            return None
        try:
            with open(path, "r", encoding="utf-8") as fp:
                entry = json.load(fp)
            return entry if isinstance(entry, dict) else None
        except Exception as e:
            logger.warning(f"Generated bio file '{path}' could not be read ({e}); it will be ignored.")
            return None

    def save(self, world_id: str, name: str, ref_id: str, entry: dict[str, Any]) -> str:
        path = self.path_for(world_id, name, ref_id)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        fd, tmp_path = tempfile.mkstemp(dir=os.path.dirname(path), suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as fp:
                json.dump(entry, fp, ensure_ascii=False, indent=2)
            os.replace(tmp_path, path)
        except Exception:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)
            raise
        return path


def make_entry(*, world_id: str, name: str, ref_id: str, base_id: str, race: str, gender: str, location: str,
               quality: str, mode: str, model: str, given_name: str, bio: str, personality_and_speech: str) -> dict[str, Any]:
    return {
        "schema": SCHEMA_VERSION,
        "source": "generated",
        "model": model,
        "created": datetime.now().isoformat(timespec="seconds"),
        "enabled": True,
        "note": "Generated by Mantella (bio_generation). Edit 'bio' / 'personality_and_speech' freely, "
                "set 'enabled' to false to use the original bio, or delete this file to regenerate.",
        "world_id": world_id,
        "name": name,
        "ref_id": ref_id,
        "base_id": base_id,
        "race": race,
        "gender": gender,
        "location": location,
        "quality": quality,
        "mode": mode,
        "given_name": given_name,
        "bio": bio,
        "personality_and_speech": personality_and_speech,
    }


def entry_text(entry: dict[str, Any]) -> str:
    text = str(entry.get("bio", "") or "").strip()
    speech = str(entry.get("personality_and_speech", "") or "").strip()
    if speech:
        text += "\nPersonality & speech: " + speech
    return text.strip()


def entry_matches(entry: dict[str, Any], name: str, race: str, gender: str) -> bool:
    """Guards against recycled ref-ids (dynamic FF-references are reused by the engine for other actors)."""
    for key, value in (("name", name), ("race", race), ("gender", gender)):
        stored = str(entry.get(key, "") or "")
        if stored and stored.lower() != str(value).lower():
            return False
    return True
